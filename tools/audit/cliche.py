# ── 4.2. Конструкції ─────────────────────────────────────────────────────────
# Порогові: одне входження нормальне, систематичне — маркер.
PATTERNS = [
    ("«не просто X, а Y»", re.compile(r"не просто [^.,;]{2,40}, а ", re.I), 2),
    ("«це не X, це Y»", re.compile(r"це не [^.,;]{2,40}, це ", re.I), 2),
    ("стопка хеджування", re.compile(r"(як правило|зазвичай|здебільшого|как правило|обычно)[^.]{0,40}(у більшості випадків|найчастіше|в большинстве случаев|зачастую)", re.I), 1),
]


def texts():
    """Тексти статей — з файлів-джерел, а не зі складеного HTML."""
    d = os.path.join(ROOT, "tools", "blog")
    if not os.path.isdir(d):
        return []
    out = []
    for f in sorted(os.listdir(d)):
        if f.startswith("art_") and f.endswith(".py"):
            out.append((f, io.open(os.path.join(d, f), encoding="utf-8").read()))
    return out


def main():
    files = texts()
    if not files:
        print("статей-джерел не знайдено")
        return 0

    total = 0
    for name, s in files:
        # Коментарі й docstring модуля не рахуємо — там мова про методичку,
        # і сама назва кліше в поясненні не є кліше в тексті.
        body = s.split('"""', 2)[-1]
        body = re.sub(r"^\s*#.*$", "", body, flags=re.M)

        hits = []
        low = body.lower()
        for group, phrases in PHRASES.items():
            for ph in phrases:
                n = low.count(ph.lower())
                if n:
                    hits.append("  %-24s «%s» — %d" % (group, ph, n))
        for label, rx, limit in PATTERNS:
            n = len(rx.findall(body))
            if n > limit:
                hits.append("  %-24s %s — %d (межа %d)" % ("конструкція", label, n, limit))

        if hits:
            total += len(hits)
            print("\n%s" % name)
            for h in hits:
                print(h)

    print()
    if total:
        print("знайдено маркерів: %d" % total)
        return 1
    print("маркерів ІІ у текстах статей не знайдено (перевірено %d файлів)" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
