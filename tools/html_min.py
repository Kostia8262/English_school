# -*- coding: utf-8 -*-
"""Прибирає з готової розмітки те, що потрібне було тільки при складанні.

Навіщо. Сторінки тут складаються з шаблонів, і в шаблонах — розлогі пояснення:
чому саме така розмітка, який баг цим закритий, чого не можна чіпати. Це
правильно, але місце тим поясненням у джерелі, а не в тому, що їде читачеві.
На головній їх набралось 318 штук на 16 КБ, на посадкових — по 2 КБ; плюс
відступи, які на посадкових дають ще стільки ж.

Кому це муляє. Не швидкості: сервер віддає сторінку стиснутою, і в gzip
відступи з коментарями майже нічого не важать. Муляє тим, хто читає сирий
HTML — GPTBot, ClaudeBot, PerplexityBot обрізають документ за обсягом, а не за
важливістю. Головна в типову межу не вкладалась, і обрізало її якраз там, де
лежить суть.

Що робить і чого не робить. Прибирає коментарі й відступи на початку рядків —
і все. Сам перевід рядка лишається, тож між двома рядковими елементами пропуск
нікуди не дівається: зібрана сторінка виглядає точно так само, без злиплих
слів. Тому тут немає ні бібліотеки, ні списку винятків.

Дві умови, на яких це тримається, перевірені на всіх 78 сторінках:
  * `<!--` не трапляється всередині `<script>` чи `<style>` — інакше
    вирізання коментаря з'їло б шматок коду;
  * умовних коментарів (`<!--[if IE]>`) на сайті немає — вони виглядають як
    коментар, але несуть розмітку.
Якщо колись з'явиться перше або друге — перевірку треба дописати сюди, а не
покладатись на те, що обійдеться.

`<pre>` і `<textarea>` на сайті не трапляються; якби трапились, зламати їх цим
правилом можна було б лише відступом усередині.

**Один виняток — `blog/index.html`.** Лістинг не складається наново, його
правлять на місці, і межі ділянки з картками позначені саме коментарями:
`<!-- КАРТКИ -->` … `<!-- /КАРТКИ -->` (`tools/blog/site_index.py`). Зрізати
їх означає зламати додавання наступної статті — причому мовчки на складанні й
голосно аж тоді, коли конвеєр мережі спробує покласти нову. Тому там
викликається `squeeze(html, keep_comments=True)`: відступи йдуть, якорі
лишаються. Якщо колись з'явиться ще один генератор, що шукає щось у власному
виході, — йому сюди ж.
"""
from __future__ import unicode_literals

import re

_COMMENT = re.compile(r"<!--.*?-->", re.S)
_INDENT = re.compile(r"\n[ \t]+")
_BLANKS = re.compile(r"\n{2,}")


def squeeze(html, keep_comments=False):
    if not keep_comments:
        html = _COMMENT.sub("", html)
    html = _INDENT.sub("\n", html)
    return _BLANKS.sub("\n", html)
