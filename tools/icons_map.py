SPARE = ("shield", "clock", "heart", "lock", "headset", "stamp", "handshake", "bulb")


def icon_name(emoji):
    """Ім'я файлу для емодзі. Невідомий — помилка збірки, не мовчазний гліф."""
    key = emoji.replace("️", "").strip()
    if key in ICONS:
        return ICONS[key]
    raise KeyError(
        "немає іконки для %r (U+%s). Домалюй її в аркуші tools/icons/sheets, "
        "наріж і додай рядок у tools/icons_map.py"
        % (emoji, " U+".join("%04X" % ord(c) for c in key))
    )


def icon(emoji, cls="w-8 h-8", size=64, lazy=True):
    """<img> замість емодзі. cls задає розмір на сторінці, size — атрибути."""
    return (
        '<img src="/icons/%s.webp" alt="" width="%d" height="%d" class="%s"%s '
        'decoding="async">'
        % (icon_name(emoji), size, size, cls, ' loading="lazy"' if lazy else "")
    )
